package pooproyect.Zona;

public class Zona {

    private String Origen;
    private String Destino;

    public Zona(String Origen, String Destino) {
        this.Origen = Origen;
        this.Destino = Destino;
    }

    public String getOrigen() {
        return Origen;
    }

    public String getDestino() {
        return Destino;
    }

}
